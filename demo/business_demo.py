"""Business demonstration: shared original clauses across supplier contracts.

Scenario
--------
Legal operations has 61 fictional supplier contracts stored as JSONL
(``data/supplier_contracts.jsonl``, generated by ``demo/make_corpus.py``).
Counsel needs, for every k, the longest run of bytes that appears verbatim
in at least k *different* contracts, to spot reusable clauses and
boilerplate drift.  One contract repeats its confidentiality clause twice
and must still count as a single source; two contracts are byte-identical
copies from different offices and do count as two sources.

The demo reads the corpus from disk (not from in-memory literals), calls
``sharedphrases.profile`` once, then independently re-verifies every
reported witness by brute substring scanning (support, length maximality,
lexicographic tie-break and earliest (doc, start)).

Run:  python3 -I demo/business_demo.py
Exit status 0 only when the verification passes.
"""

from __future__ import annotations

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from sharedphrases import profile  # noqa: E402

CORPUS = os.path.join(ROOT, "data", "supplier_contracts.jsonl")


def load_corpus():
    with open(CORPUS, "r", encoding="ascii") as handle:
        rows = [json.loads(line) for line in handle if line.strip()]
    documents = [row["text"].encode("ascii") for row in rows]
    return rows, documents


def count_support(documents, piece):
    return sum(1 for doc in documents if piece in doc)


def support_table(documents, length):
    """Support count for each distinct length-byte piece (bounded work)."""
    table: dict = {}
    for doc in documents:
        seen = set()
        for start in range(len(doc) - length + 1):
            piece = doc[start:start + length]
            if piece in seen:
                continue
            seen.add(piece)
            table[piece] = table.get(piece, 0) + 1
    return table


def verify(documents, results):
    """Independent check of each answer, without using the suffix index."""
    checks = 0
    for slot, item in enumerate(results):
        k = slot + 2
        if item is None:
            continue
        length = item["length"]
        doc, start = item["doc"], item["start"]
        piece = documents[doc][start:start + length]
        assert len(piece) == length and length > 0, (k, item)

        here = support_table(documents, length)
        longer = support_table(documents, length + 1)
        assert here[piece] >= k, (k, item, "support")

        contenders = [p for p, c in here.items() if c >= k]
        assert piece == min(contenders), (k, "lexicographic tie break")

        earliest = min(
            (dd, ss)
            for dd, text in enumerate(documents)
            for ss in range(len(text) - length + 1)
            if text[ss:ss + length] == piece
        )
        assert earliest == (doc, start), (k, "witness", earliest)
        assert max(longer.values(), default=0) < k, (k, "not maximal")
        checks += 1
    return checks


def main():
    rows, documents = load_corpus()
    total = sum(len(d) for d in documents)
    print(f"corpus: {len(documents)} contracts, {total} bytes, "
          f"N = {total + len(documents)}")
    print(f"source: {os.path.relpath(CORPUS, ROOT)} (JSONL, one contract per line)")

    results = profile(documents)

    print("\nk -> longest shared original run (at least k distinct contracts)")
    for slot, item in enumerate(results):
        k = slot + 2
        if item is None:
            print(f"  k={k:2d}: (none)")
            continue
        piece = documents[item["doc"]][item["start"]:item["start"] + item["length"]]
        summary = piece[:96].decode("ascii").replace("\n", " ")
        if k <= 3 or k >= 55 or k in (10, 20, 30, 40, 50):
            print(f"  k={k:2d}: len={item['length']:4d} "
                  f"witness=(doc={item['doc']}, start={item['start']})")
            print(f"        {summary}")

    checked = verify(documents, results)
    print(f"\nindependent re-verification passed for {checked} non-None "
          f"answers (support, maximality, lexicographic tie-break, witness).")

    for k in (2, 10, 30, 61):
        item = results[k - 2]
        if item is None:
            continue
        piece = documents[item["doc"]][item["start"]:item["start"] + item["length"]]
        support = count_support(documents, piece)
        print(f"  k={k:2d}: {item['length']} bytes shared, actual support="
              f"{support} contracts")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
